import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceArg = process.argv.indexOf("--source");
const source = path.resolve(sourceArg < 0 ? path.join(root, "../ogl-upstream") : process.argv[sourceArg + 1]);
const revision = "385ce65c352c70734a36dc98c787fdd1d30ddb3b";
if (execFileSync("git", ["-C", source, "rev-parse", "HEAD"], { encoding: "utf8" }).trim() !== revision) {
  throw new Error("Expected the pinned OGL revision " + revision);
}
if (execFileSync("git", ["-C", source, "status", "--porcelain", "--", "src", "examples", "README.md"], { encoding: "utf8" }).trim()) {
  throw new Error("The pinned source must have a clean working tree");
}
const components = JSON.parse(fs.readFileSync(path.join(root, "scripts/webgl-components.json"), "utf8"));
const hash = data => createHash("sha256").update(data).digest("hex");
function write(name, data) {
  const destination = path.join(root, name);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, data);
}
const manifest = { version: 1, upstream: { repository: "oframe/ogl", revision, version: "1.0.11" }, assets: {}, components: {} };
const provenance = { upstream: manifest.upstream, components: {} };
const credits = [];
for (const component of components) {
  const original = fs.readFileSync(path.join(source, "examples", component.id + ".html"), "utf8");
  write("vendor/ogl/examples/" + component.id + ".html", original);
  let script = original.match(/<script type="module">([\s\S]*?)<\/script>/)[1];
  const imports = script.match(/import\s*\{([^}]+)\}\s*from\s*['"][^'"]+['"];?/)[1].trim();
  script = script.replace(/import\s*\{[^}]+\}\s*from\s*['"][^'"]+['"];?/, "");
  // Only rewrite asset literals and async lifecycle boundaries. GLSL stays byte-for-byte identical.
  script = script.replace(/(['"\x60])(assets\/[\w./-]+)\1/g, (_, quote, asset) => "context.asset(" + JSON.stringify(asset) + ")");
  const ast = ts.createSourceFile("scene.js", script, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  const edits = [];
  function visit(node) {
    if ((ts.isFunctionDeclaration(node) || ts.isFunctionExpression(node)) &&
        node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.AsyncKeyword) && node.body) {
      edits.push({ position: node.body.getStart(ast) + 1, text: "\nconst finishTask = context.beginTask();\ntry {\n" });
      edits.push({ position: node.body.end - 1, text: "\n} catch (error) { context.fail(error); } finally { finishTask(); }\n" });
    }
    ts.forEachChild(node, visit);
  }
  visit(ast);
  for (const edit of edits.sort((a, b) => b.position - a.position)) {
    script = script.slice(0, edit.position) + edit.text + script.slice(edit.position);
  }
  const scopedGlobals = ["window", "document", "Image", "fetch", "requestAnimationFrame", "performance"]
    .filter(name => new RegExp("\\b" + name + "\\b").test(script));
  const native = "// FlexUI native scene. Provenance and asset credits: public/webgl/ATTRIBUTION.md.\n" +
    "// Generated by scripts/sync-webgl.mjs; original rendering math and shaders are preserved.\n" +
    "export default function mountScene(context) {\n" +
    "  const { " + imports + " } = context.ogl;\n" +
    "  const { " + scopedGlobals.join(", ") + " } = context;\n" +
    script + "\n}\n";
  write("components/flexui/webgl/scenes/" + component.id + ".js", native);
  write("components/flexui/webgl/scenes/" + component.id + ".d.ts",
    'import type { WebGLSceneSetup } from "../types";\ndeclare const mountScene: WebGLSceneSetup;\nexport default mountScene;\n');
  write("components/flexui/" + component.id + ".tsx",
    '"use client";\n\nimport { WebGLCanvas, type WebGLComponentProps } from "./webgl-canvas";\n' +
    'import scene from "./webgl/scenes/' + component.id + '.js";\n\n' +
    "export type " + component.component + "Props = WebGLComponentProps;\n\n" +
    "export function " + component.component + "(props: " + component.component + "Props) {\n" +
    '  return <WebGLCanvas {...props} component="' + component.id + '" title="' + component.title + '" scene={scene} />;\n}\n');
  const cliName = component.id.split("-").map(part => part[0].toUpperCase() + part.slice(1)).join("");
  if (cliName !== component.component) {
    fs.appendFileSync(path.join(root, "components/flexui/" + component.id + ".tsx"), "\nexport { " + component.component + " as " + cliName + " };\n");
  }
  provenance.components[component.id] = { originalSha256: hash(original), nativeSha256: hash(native) };
  const assets = new Set([...original.matchAll(/assets\/[\w./-]+\.(?:jpg|png|json|glb|js)/g)].map(match => match[0]));
  assets.delete("assets/favicon.png");
  if ([...assets].some(name => name.startsWith("assets/libs/basis/"))) {
    assets.add("assets/libs/basis/basis_transcoder.js");
    assets.add("assets/libs/basis/basis_transcoder.wasm");
  }
  manifest.components[component.id] = [];
  for (const asset of [...assets].sort()) {
    const data = fs.readFileSync(path.join(source, "examples", asset));
    const target = "public/webgl/" + asset;
    write(target, data);
    manifest.assets[target] = {
      path: target, bytes: data.length, sha256: hash(data),
      url: "https://raw.githubusercontent.com/oframe/ogl/" + revision + "/examples/" + asset,
    };
    manifest.components[component.id].push(target);
  }
  const info = original.match(/<div class="Info"[^>]*>([\s\S]*?)<\/div>/)?.[1] ?? "";
  const links = [...info.matchAll(/<a href="([^"]+)"[^>]*>([^<]+)<\/a>/g)]
    .filter(match => !match[1].startsWith("/")).map(match => "- [" + match[2] + "](" + match[1] + ")").join("\n");
  credits.push("## " + component.title + "\n\n" + info.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim() + "\n" + links);
}
write("public/webgl/assets-manifest.json", JSON.stringify(manifest, null, 2) + "\n");
write("public/webgl/provenance.json", JSON.stringify(provenance, null, 2) + "\n");
write("public/webgl/ATTRIBUTION.md",
  "# FlexUI WebGL component attribution\n\nRendering code adapted from OGL by Nathan Gordon and contributors, version 1.0.11, revision " + revision +
  ". Library and scene code are distributed under the upstream Unlicense; see UNLICENSE.txt. Models, photographs, textures and decoders retain their original creators' terms and credits. Credits are collected here rather than overlaid on component previews.\n\n" +
  credits.join("\n\n") + "\n");
write("lib/webgl-components.ts",
  "// Generated from scripts/webgl-components.json by sync-webgl.mjs.\n" +
  "export const WEBGL_COMPONENTS = " + JSON.stringify(components, null, 2) + " as const;\n\n" +
  'export type WebGLComponentId = (typeof WEBGL_COMPONENTS)[number]["id"];\n' +
  "export function getWebGLComponent(id: string) { return WEBGL_COMPONENTS.find(component => component.id === id); }\n");
console.log("Prepared " + components.length + " native FlexUI components and " + Object.keys(manifest.assets).length + " verified assets.");
